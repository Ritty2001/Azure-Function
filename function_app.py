import azure.functions as func
import logging

app = func.FunctionApp()

@app.route(route="HttpToBlob", auth_level=func.AuthLevel.FUNCTION)
@app.blob_output(
    arg_name="outputblob",
    path="demo-container/{rand-guid}.txt",
    connection="AzureWebJobsStorage"
)
def HttpToBlob(req: func.HttpRequest, outputblob: func.Out[str]) -> func.HttpResponse:
    name = req.params.get('name')
    if not name:
        return func.HttpResponse(
            "Pass a name in the query string, e.g. ?name=Ritty",
            status_code=400
        )

    content = f"Hello, {name}! This file was generated by an Azure Function."
    outputblob.set(content)

    return func.HttpResponse(f"Blob created for {name}. Check your storage container.")